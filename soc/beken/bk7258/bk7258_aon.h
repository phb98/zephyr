/*
 * Always-on (AON) power management unit, RTC and watchdog registers. Addresses
 * are the secure aliases; the non-secure alias of each is at +0x10000000.
 */

#ifndef _SOC_BEKEN_BK7258_BK7258_AON_H_
#define _SOC_BEKEN_BK7258_BK7258_AON_H_

#include <zephyr/sys/util_macro.h>

#define BK7258_AON_PMU_BASE 0x44000000
#define BK7258_AON_RTC_BASE 0x44000200
#define BK7258_AON_WDT_BASE 0x44000600

/* PMU */

#define BK7258_AON_PMU_R0                       (BK7258_AON_PMU_BASE + 0x000)
#define BK7258_AON_PMU_R0_MEMCHK_BPS            BIT(0)
#define BK7258_AON_PMU_R0_FAST_BOOT             BIT(1)
#define BK7258_AON_PMU_R0_OTA_FINISH            BIT(2)
#define BK7258_AON_PMU_R0_BL2_DEEP_SLEEP        BIT(3)
#define BK7258_AON_PMU_R0_GPIO_RETENTION_BITMAP GENMASK(19, 12)
#define BK7258_AON_PMU_R0_RESET_REASON          GENMASK(30, 24)
#define BK7258_AON_PMU_R0_GPIO_SLEEP            BIT(31)

#define BK7258_AON_PMU_R1                (BK7258_AON_PMU_BASE + 0x004)
#define BK7258_AON_PMU_R1_TOUCH_SELECT   GENMASK(3, 0)
#define BK7258_AON_PMU_R1_TOUCH_INT_EN   GENMASK(19, 4)
#define BK7258_AON_PMU_R1_USBPLUG_INT_EN BIT(20)
#define BK7258_AON_PMU_R1_CLK_MOD        BIT(21)

#define BK7258_AON_PMU_R2              (BK7258_AON_PMU_BASE + 0x008)
#define BK7258_AON_PMU_R2_WDT_RST_ANA  BIT(0)
#define BK7258_AON_PMU_R2_WDT_RST_TOP  BIT(1)
#define BK7258_AON_PMU_R2_WDT_RST_AON  BIT(2)
#define BK7258_AON_PMU_R2_WDT_RST_AWT  BIT(3)
#define BK7258_AON_PMU_R2_WDT_RST_GPIO BIT(4)
#define BK7258_AON_PMU_R2_WDT_RST_RTC  BIT(5)
#define BK7258_AON_PMU_R2_WDT_RST_WDT  BIT(6)
#define BK7258_AON_PMU_R2_WDT_RST_PMU  BIT(7)
#define BK7258_AON_PMU_R2_WDT_RST_PHY  BIT(8)

#define BK7258_AON_PMU_R3       (BK7258_AON_PMU_BASE + 0x00c)
#define BK7258_AON_PMU_R3_SD_EN BIT(31)

#define BK7258_AON_PMU_R40             (BK7258_AON_PMU_BASE + 0x100)
#define BK7258_AON_PMU_R40_WAKE1_DELAY GENMASK(3, 0)
#define BK7258_AON_PMU_R40_WAKE2_DELAY GENMASK(7, 4)
#define BK7258_AON_PMU_R40_WAKE3_DELAY GENMASK(11, 8)
#define BK7258_AON_PMU_R40_HALT1_DELAY GENMASK(15, 12)
#define BK7258_AON_PMU_R40_HALT2_DELAY GENMASK(19, 16)
#define BK7258_AON_PMU_R40_HALT3_DELAY GENMASK(23, 20)
#define BK7258_AON_PMU_R40_HALT_VOLT   BIT(24)
#define BK7258_AON_PMU_R40_HALT_XTAL   BIT(25)
#define BK7258_AON_PMU_R40_HALT_CORE   BIT(26)
#define BK7258_AON_PMU_R40_HALT_FLASH  BIT(27)
#define BK7258_AON_PMU_R40_HALT_ROSC   BIT(28)
#define BK7258_AON_PMU_R40_HALT_RESTEN BIT(29)
#define BK7258_AON_PMU_R40_HALT_ISOLAT BIT(30)
#define BK7258_AON_PMU_R40_HALT_CLKENA BIT(31)

#define BK7258_AON_PMU_R41               (BK7258_AON_PMU_BASE + 0x104)
#define BK7258_AON_PMU_R41_LPO_CONFIG    GENMASK(1, 0)
#define BK7258_AON_PMU_R41_FLSHSCK_IOCAP GENMASK(3, 2)
#define BK7258_AON_PMU_R41_WAKEUP_ENA    GENMASK(9, 4)
#define BK7258_AON_PMU_R41_IO_DRV        GENMASK(11, 10)
#define BK7258_AON_PMU_R41_XTAL_SEL      BIT(14)
#define BK7258_AON_PMU_R41_HALT_LPO      BIT(24)
#define BK7258_AON_PMU_R41_HALT_BUSRST   BIT(25)
#define BK7258_AON_PMU_R41_HALT_BUSISO   BIT(26)
#define BK7258_AON_PMU_R41_HALT_BUSPWD   BIT(27)
#define BK7258_AON_PMU_R41_HALT_BLPISO   BIT(28)
#define BK7258_AON_PMU_R41_HALT_BLPPWD   BIT(29)
#define BK7258_AON_PMU_R41_HALT_WLPISO   BIT(30)
#define BK7258_AON_PMU_R41_HALT_WLPPWD   BIT(31)

#define BK7258_AON_PMU_R43                 (BK7258_AON_PMU_BASE + 0x10c)
#define BK7258_AON_PMU_R43_CLR_INT_TOUCHED GENMASK(15, 0)
#define BK7258_AON_PMU_R43_CLR_INT_USBPLUG BIT(16)
#define BK7258_AON_PMU_R43_CLR_WAKEUP      BIT(17)

#define BK7258_AON_PMU_R70             (BK7258_AON_PMU_BASE + 0x1c0)
#define BK7258_AON_PMU_R70_INT_TOUCHED GENMASK(15, 0)
#define BK7258_AON_PMU_R70_INT_USBPLUG BIT(16)

#define BK7258_AON_PMU_R71               (BK7258_AON_PMU_BASE + 0x1c4)
#define BK7258_AON_PMU_R71_TOUCH_STATE   GENMASK(15, 0)
#define BK7258_AON_PMU_R71_USBPLUG_STATE BIT(16)
#define BK7258_AON_PMU_R71_WAKEUP_SOURCE GENMASK(24, 20)

#define BK7258_AON_PMU_R72            (BK7258_AON_PMU_BASE + 0x1c8)
#define BK7258_AON_PMU_R72_VDW_SOFT1V GENMASK(15, 0)
#define BK7258_AON_PMU_R72_VUP_SOFT1V GENMASK(31, 16)

#define BK7258_AON_PMU_R73               (BK7258_AON_PMU_BASE + 0x1cc)
#define BK7258_AON_PMU_R73_MUL_TOUCH_INT GENMASK(15, 0)
#define BK7258_AON_PMU_R73_WAKE_UP_SOFT  BIT(16)
#define BK7258_AON_PMU_R73_CAP_CAL       GENMASK(25, 17)
#define BK7258_AON_PMU_R73_CAL_DONE      BIT(26)

#define BK7258_AON_PMU_R7C    (BK7258_AON_PMU_BASE + 0x1f0)
#define BK7258_AON_PMU_R7C_ID GENMASK(31, 0)

#define BK7258_AON_PMU_R7D                (BK7258_AON_PMU_BASE + 0x1f4)
#define BK7258_AON_PMU_R7D_LCAL           GENMASK(7, 0)
#define BK7258_AON_PMU_R7D_L              BIT(8)
#define BK7258_AON_PMU_R7D_ADC_CAL        GENMASK(14, 9)
#define BK7258_AON_PMU_R7D_BGCAL          GENMASK(20, 15)
#define BK7258_AON_PMU_R7D_PLL_26M_UNLOCK BIT(21)
#define BK7258_AON_PMU_R7D_DPLL_UNLOCK    BIT(22)
#define BK7258_AON_PMU_R7D_H1             GENMASK(31, 23)

#define BK7258_AON_PMU_R7E            (BK7258_AON_PMU_BASE + 0x1f8)
#define BK7258_AON_PMU_R7E_CBCAL      GENMASK(4, 0)
#define BK7258_AON_PMU_R7E_AD_STATE   GENMASK(8, 5)
#define BK7258_AON_PMU_R7E_TD_STATES1 GENMASK(21, 9)
#define BK7258_AON_PMU_R7E_H2         GENMASK(31, 22)

#define BK7258_AON_PMU_R7F            (BK7258_AON_PMU_BASE + 0x1fc)
#define BK7258_AON_PMU_R7F_TD_STATES2 GENMASK(31, 0)

/* RTC: a 64-bit tick counter, split into low and high words */

#define BK7258_AON_RTC_CTRL              (BK7258_AON_RTC_BASE + 0x00)
#define BK7258_AON_RTC_CTRL_CNT_RESET    BIT(0)
#define BK7258_AON_RTC_CTRL_CNT_STOP     BIT(1)
#define BK7258_AON_RTC_CTRL_UP_INT_EN    BIT(2)
#define BK7258_AON_RTC_CTRL_TICK_INT_EN  BIT(3)
#define BK7258_AON_RTC_CTRL_UP_INT_STS   BIT(4)
#define BK7258_AON_RTC_CTRL_TICK_INT_STS BIT(5)
#define BK7258_AON_RTC_CTRL_EN           BIT(6)

#define BK7258_AON_RTC_UPPER_VAL       (BK7258_AON_RTC_BASE + 0x04)
#define BK7258_AON_RTC_TICK_VAL        (BK7258_AON_RTC_BASE + 0x08)
#define BK7258_AON_RTC_COUNTER_VAL     (BK7258_AON_RTC_BASE + 0x0c)
#define BK7258_AON_RTC_UP_VAL_LPO      (BK7258_AON_RTC_BASE + 0x10)
#define BK7258_AON_RTC_TICK_VAL_LPO    (BK7258_AON_RTC_BASE + 0x14)
#define BK7258_AON_RTC_UPPER_VAL_HI    (BK7258_AON_RTC_BASE + 0x18)
#define BK7258_AON_RTC_TICK_VAL_HI     (BK7258_AON_RTC_BASE + 0x1c)
#define BK7258_AON_RTC_UP_VAL_LPO_HI   (BK7258_AON_RTC_BASE + 0x20)
#define BK7258_AON_RTC_TICK_VAL_LPO_HI (BK7258_AON_RTC_BASE + 0x24)
#define BK7258_AON_RTC_COUNTER_VAL_HI  (BK7258_AON_RTC_BASE + 0x28)

/* Watchdog: the control word is written twice, with KEY_1ST and then KEY_2ND */

#define BK7258_AON_WDT_CTRL         (BK7258_AON_WDT_BASE + 0x00)
#define BK7258_AON_WDT_CTRL_PERIOD  GENMASK(15, 0)
#define BK7258_AON_WDT_CTRL_KEY     GENMASK(23, 16)
#define BK7258_AON_WDT_KEY_1ST      0x5a
#define BK7258_AON_WDT_KEY_2ND      0xa5

#endif /* _SOC_BEKEN_BK7258_BK7258_AON_H_ */
